//! JNI boundary for `ai.choosh.NativeBridge`. Every native method here is a
//! thin marshaling wrapper (string in, string out, or a handle) around
//! [`engine::Engine`] — no relay/`WebAuthn` logic lives in this file, only
//! JSON string round-tripping and the opaque-handle registry below.
//!
//! Every export uses fixed-width integers or `JString` only. No raw
//! pointer crosses the ABI: `nativeInit` returns a small integer handle,
//! looked up in a process-global registry, not a transmuted `Box` pointer —
//! the same discipline the crate this replaces used, for the same reason
//! (a raw handle-as-pointer is one JNI misuse away from real memory
//! corruption; an integer lookup key isn't).

