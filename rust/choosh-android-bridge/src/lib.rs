#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn unknown_handle_is_reported_not_panicked() {
        assert_eq!(with_handle(999_999, "absent".to_string(), |_| "present".to_string()), "absent");
    }

    #[test]
    fn handles_are_unique_and_monotonic() {
        let a = NEXT_HANDLE.fetch_add(1, Ordering::Relaxed);
        let b = NEXT_HANDLE.fetch_add(1, Ordering::Relaxed);
        assert!(b > a);
    }
}
