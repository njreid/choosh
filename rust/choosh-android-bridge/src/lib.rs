use tokio::runtime::Runtime;

struct EngineHandle {
    engine: Arc<Engine>,
    runtime: Runtime,
}

static ENGINES: LazyLock<Mutex<HashMap<i64, EngineHandle>>> = LazyLock::new(|| Mutex::new(HashMap::new()));
static NEXT_HANDLE: AtomicI64 = AtomicI64::new(1);

fn error_json(message: &str) -> String {
    serde_json::json!({ "error": message }).to_string()
}

fn jstring_to_string(env: &Env<'_>, value: &JString<'_>) -> Result<String, jni::errors::Error> {
    Ok(value.mutf8_chars(env)?.to_string())
}

fn with_handle<T>(handle: jlong, absent: T, present: impl FnOnce(&EngineHandle) -> T) -> T {
    let engines = ENGINES.lock().unwrap_or_else(std::sync::PoisonError::into_inner);
    engines.get(&handle).map_or(absent, present)
}

/// Lets `terminal_jni.rs` reach the single shared [`engine::Engine`]/
/// `PhoneConnection` behind a connection handle to open a PTY tunnel,
/// reusing `Engine::open_pty_tunnel` rather than opening a second
/// `PhoneConnection`. Not exposed outside this crate.
#[cfg(target_os = "android")]
pub(crate) fn with_connection_engine<T>(handle: jlong, present: impl FnOnce(&Engine, &Runtime) -> T) -> Option<T> {
    let engines = ENGINES.lock().unwrap_or_else(std::sync::PoisonError::into_inner);
    engines.get(&handle).map(|h| present(&h.engine, &h.runtime))
}

/// Like [`with_connection_engine`], but returns a cloned `Arc<Engine>`
/// instead of handing a borrow into a synchronous closure — what
/// `gateway_jni.rs` needs, since a gateway's per-connection `opener`
/// closures call `Engine` methods from *their own* async tasks (potentially
/// running on a different `Runtime` than the connection's own), where
/// re-entering the connection's `Runtime` via `block_on` would panic
/// ("Cannot start a runtime from within a runtime"). `Engine`'s own methods
/// only touch runtime-agnostic `tokio::sync` primitives internally (see
/// `PhoneConnection`'s module docs), so calling them directly from any
/// runtime context is safe — no `block_on` needed here at all.
#[cfg(target_os = "android")]
pub(crate) fn connection_engine_arc(handle: jlong) -> Option<Arc<Engine>> {
    let engines = ENGINES.lock().unwrap_or_else(std::sync::PoisonError::into_inner);
    engines.get(&handle).map(|h| Arc::clone(&h.engine))
}

// `native_method!`'s generated wrapper calls these implementation functions
// with the exact `JString` (by-value) parameter types declared in the
// macro invocations below — narrowing these to `&JString` would mismatch
// that generated call site, so the by-value params clippy would otherwise
// flag here are load-bearing, not an oversight.
#[allow(clippy::needless_pass_by_value)]
fn native_init<'local>(env: &mut Env<'local>, _class: JClass<'local>, http_base_url: JString<'local>, ws_url: JString<'local>) -> Result<jlong, jni::errors::Error> {
    let http_base_url = jstring_to_string(env, &http_base_url)?;
    let ws_url = jstring_to_string(env, &ws_url)?;
    let Ok(runtime) = Runtime::new() else {
        // No handle to return that would make this recoverable from
        // Kotlin's side in a meaningful way — a failed OS thread-pool
        // creation is not something a retry fixes. Every other native
        // method here treats "handle not found" the same as "engine
        // failed to initialize", so returning 0 is safe and consistent.
        return Ok(0);
    };
    let engine = Arc::new(Engine::new(http_base_url, ws_url));
    let handle = NEXT_HANDLE.fetch_add(1, Ordering::Relaxed);
    ENGINES
        .lock()
        .unwrap_or_else(std::sync::PoisonError::into_inner)
        .insert(handle, EngineHandle { engine, runtime });
    Ok(handle)
}

